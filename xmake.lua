set_xmakever("3.0.7")
if is_plat("wasm") then
    raise("this project does not support WASM!")
end

local buildaux = os.projectdir() .. "/../pascal-xmake-aux/"
add_moduledirs(buildaux .. "utils")
add_repositories("3rd 3rdparty", { rootdir = buildaux })
add_imports("miscs", "targets")

option("output-prefix")
    set_showmenu(true)
    set_description("Prefix for built binaries - useful for co-use with ones like GNU Coreutils")
    set_default("cc-")
option_end()
includes(buildaux .. "options.lua")

add_requires("lua >=5.5.0", { configs = { shared = true } })
add_requires("gettext", { optional = false })
add_requires("scdoc", { optional = true })

add_rules("mode.debug", "mode.release")
set_policy("check.auto_ignore_flags", false)

toolchain("fpc-nolibc")
    -- Adding -k-lc somehow made FPC to put --dynamic-linker=... into link
    -- flags (shown in the script generated by compiler's -st flag).
    -- The thing is that not all targets have the same thing, which caused
    -- unfunny error that took me hours to figure out.
    -- Linux only (who asked for this?).
    set_description("Free Pascal compiler without the implicit -k-lc link flag on UNIX")
    set_toolset("pc",   "$(env PC)", "fpc")
    set_toolset("pcld", "$(env PC)", "fpc")
    set_toolset("pcsh", "$(env PC)", "fpc")
toolchain_end()

for _, dir in ipairs(os.dirs("src/*")) do
	local name = path.filename(dir)
    local srcfile = "src/" .. name .. "/" .. name .. ".pp"

	if not os.isfile(srcfile) then
        goto continue
    end

    target(name)
        set_kind("binary")
        set_toolchains("fpc-nolibc")
        add_files(srcfile)

        if name == "dir" then
            add_packages("lua", {links = "lua"})
        end

        on_load(function (target)
            target:add("pcflags", "@build-aux/cc.cfg")
            target:add("pcflags", "-Fisrc/" .. name)
            target:add("pcflags", "-Fiinclude/")
            target:add("pcflags", "-Fusrc/shared")
            if has_config("output-prefix") then
                target:set("basename", get_config("output-prefix") .. name)
            end
            targets.on_target_load(target)
        end)

        before_build(function (target)
            targets.before_target_build(target, os.projectdir() .. "/i18n/%s/", name .. ".mo")
        end)

        before_install(function (target)
            targets.before_target_install(target)
            target:add("installfiles", "docs/cc-" .. name .. ".1", {
                prefixdir = "share/man/man1",
                name = get_config("output-prefix") ..  name .. ".1"
            })
        end)

    ::continue::
end

includes(
    buildaux .. "tasks/docs",
    buildaux .. "tasks/i18n"
)
